"""
Práctica Loop For 1:

Utilizando loops For, saluda a todos los miembros de una clase, imprimiendo "Hola" + su nombre.
- Por ejemplo: "Hola María"
- alumnos_clase = ["María", "José", "Carlos", "Martina", "Isabel", "Tomás", "Daniela"]
"""
students_class = ["María", "José", "Carlos", "Martina", "Isabel", "Tomás", "Daniela"]

for student in students_class:
    print(f"Hola {student}")
